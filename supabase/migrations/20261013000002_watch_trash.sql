-- Recently Deleted: cards and Telegram recipients removed on the admin page, restorable for 30 days.
create table public.watch_trash (
  id bigint generated always as identity primary key,
  kind text not null check (kind in ('card', 'recipient')),
  data jsonb not null,
  deleted_at timestamptz not null default now()
);
alter table public.watch_trash enable row level security;
revoke all on public.watch_trash from anon, authenticated;

-- Lets a restored card keep its original id.
alter table public.watch_cards alter column id set generated by default;
